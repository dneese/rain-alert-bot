function t(lang, key, params = {}) {
  const translations_obj = translations[lang] || translations.uk;
  let text = translations_obj[key] || translations.uk[key] || key;
  for (const [param, value] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${param}\\}`, 'g'), value);
  }
  return text;
}

